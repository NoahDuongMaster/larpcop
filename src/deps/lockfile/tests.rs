//! Samples are real lockfiles (npm 11, pnpm 11, uv 0.11, cargo 1.98, bun 1.4), trimmed,
//! plus private, git and workspace entries that must be skipped.

use super::js::pnpm_key;
use super::*;

fn pins(file: &str, content: &str) -> Vec<String> {
    let mut out: Vec<String> = parse(file, content)
        .expect("is a lockfile")
        .expect("parses")
        .iter()
        .map(|p| format!("{}:{p}", p.eco))
        .collect();
    out.sort();
    out
}

const NPM: &str = r#"{
  "name": "t", "version": "1.0.0", "lockfileVersion": 3, "requires": true,
  "packages": {
    "": { "name": "t", "version": "1.0.0", "dependencies": { "left-pad": "^1.3.0" } },
    "node_modules/@isaacs/string-locale-compare": {
      "version": "1.1.0",
      "resolved": "https://registry.npmjs.org/@isaacs/string-locale-compare/-/string-locale-compare-1.1.0.tgz"
    },
    "node_modules/left-pad": {
      "version": "1.3.0",
      "resolved": "https://registry.npmjs.org/left-pad/-/left-pad-1.3.0.tgz"
    },
    "node_modules/a/node_modules/left-pad": { "version": "1.2.0" },
    "node_modules/pad": { "name": "left-pad", "version": "1.1.0" },
    "node_modules/@acme/ui": {
      "version": "2.0.0", "resolved": "https://npm.acme.internal/@acme/ui/-/ui-2.0.0.tgz"
    },
    "node_modules/app": { "resolved": "packages/app", "link": true },
    "packages/app": { "version": "0.0.1" }
  }
}"#;

#[test]
fn npm_lock() {
    assert_eq!(
        pins("package-lock.json", NPM),
        [
            "npm:@isaacs/string-locale-compare@1.1.0",
            "npm:left-pad@1.1.0",
            "npm:left-pad@1.2.0",
            "npm:left-pad@1.3.0"
        ]
    );
    let p = Pinned::new(Ecosystem::Npm, "left-pad", "1.3.0");
    assert_eq!(line_of("package-lock.json", NPM, &p), 9);
    let v1 = r#"{"lockfileVersion": 1, "dependencies": {}}"#;
    assert!(parse("package-lock.json", v1).unwrap().is_err());
}

const PNPM_V9: &str = "lockfileVersion: '9.0'

importers:

  .:
    dependencies:
      left-pad:
        specifier: 1.3.0
        version: 1.3.0

packages:

  '@isaacs/string-locale-compare@1.1.0':
    resolution: {integrity: sha512-SQ7K==}

  left-pad@1.3.0:
    resolution: {integrity: sha512-XI5M==}
    deprecated: use String.prototype.padStart()

  '@acme/ui@2.0.0':
    resolution: {tarball: https://npm.acme.internal/@acme/ui/-/ui-2.0.0.tgz}

  forked@https://codeload.github.com/acme/forked/tar.gz/abc123:
    resolution: {tarball: https://codeload.github.com/acme/forked/tar.gz/abc123}
    version: 1.0.0

snapshots:

  left-pad@1.3.0: {}
";

#[test]
fn pnpm_lock() {
    assert_eq!(
        pins("pnpm-lock.yaml", PNPM_V9),
        [
            "npm:@isaacs/string-locale-compare@1.1.0",
            "npm:left-pad@1.3.0"
        ]
    );
    assert_eq!(
        pnpm_key("/react-dom@18.2.0(react@18.2.0)"),
        Some(("react-dom", "18.2.0"))
    );
    assert_eq!(
        pnpm_key("/@babel/core/7.24.0"),
        Some(("@babel/core", "7.24.0"))
    );
    assert_eq!(pnpm_key("/foo/1.0.0_react@17.0.0"), Some(("foo", "1.0.0")));
    assert_eq!(
        pnpm_key("/@types/node@22.1.0"),
        Some(("@types/node", "22.1.0"))
    );
    assert_eq!(pnpm_key("link:../x"), None);
}

